#include <stdio.h>

int main()
{
    // 示例1：&& 的短路
    int a = 0, b = 5;
    if (a != 0 && (b = 3)) 
    {
        // 左边 a!=0 结果是假，右边 (b=3) 被短路，不会执行
    }
    printf("&&短路示例，b = %d\n", b); // 输出 5

    // 示例2：|| 的短路
    int x = 1, y = 10;
    if (x == 1 || (y = 20))
    {
        // 左边x==1为真，右边(y=20)被短路，不执行
    }
    printf("||短路示例，y = %d\n", y); // 输出10

    // 示例3：对比，没有发生短路的情况
    int m = 2, n = 100;
    if (m > 0 && (n = 200))
    {
        // 左边m>0为真，会执行右边n=200
    }
    printf("无短路示例，n = %d\n", n); // 输出200

    return 0;
}

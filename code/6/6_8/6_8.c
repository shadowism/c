#include <stdio.h>

int main()
{
    int a = 10;

    // ❌ 野指针：只定义不赋值，里面是随机无效地址
    // int *p1;
    // *p1 = 20; // 极度危险！随机篡改内存，大概率直接崩溃

    // ✅ 正确做法：暂时不用的指针，初始化为NULL（地址0）
    int *p = NULL;
    printf("空指针的地址值：%p\n", p);

    // 指针明确指向有效变量后，才能使用
    p = &a;
    // 使用前先判空，养成安全习惯
    if (p != NULL)
    {
        printf("指针有效，指向的值：%d\n", *p);
    }

    return 0;
}
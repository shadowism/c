#include <stdio.h>

int main()
{
    int arr[3] = {1, 2, 3};
    int *p = arr;

    // ✅ 指针变量可以自增、可以修改
    p++; 
    printf("p自增后指向的值：%d\n", *p); // 输出2

    // ❌ 数组名不能修改！下面这行如果放开会直接编译报错
    // arr++; 
    // 原因：arr是地址常量，就像数字100，你不能写 100++

    // ✅ 但数组名可以参与运算（不修改自身）
    printf("arr+1指向的值：%d\n", *(arr+1)); // 输出2

    return 0;
}